class PokemonLoad_Scene
  def pbStartScene(commands, show_continue, trainer, stats, map_id)
    @commands = commands
    @sprites = {}
    @viewport = Viewport.new(0, 0, Graphics.width, Graphics.height)
    @viewport.z = 99998
    @sprites["background"]=ColoredPlane.new(Color.new(248,248,248),@viewport)
    @sprites["cmdwindow"] = Window_CommandPokemon.new(commands)
    @sprites["cmdwindow"].viewport = @viewport
    @sprites["cmdwindow"].visible  = true
    @sprites["infowindow"]=Window_AdvancedTextPokemon.newWithSize(
                            "",0,Graphics.height-64,Graphics.width,64,@viewport)
    @sprites["infowindow"].letterbyletter=false
    @sprites["infowindow"].viewport=@viewport
    @sprites["infowindow"].visible=show_continue
    if show_continue
      totalsec = stats&.play_time.to_i || 0
      hour = totalsec / 60 / 60
      min  = totalsec / 60 % 60
      if hour>0
        time=_INTL("{1}h {2}m",hour,min)
      else
          time=_INTL("{1}m",min)
      end
      @sprites["infowindow"].setText(_INTL("Time: {1}",time))
    end
  end

  def pbStartScene2
    pbFadeInAndShow(@sprites) { pbUpdate }
  end

  def pbStartDeleteScene
    @sprites = {}
    @viewport = Viewport.new(0, 0, Graphics.width, Graphics.height)
    @viewport.z = 99998
    @sprites["background"]=ColoredPlane.new(Color.new(248,248,248),@viewport)
  end

  def pbUpdate
    pbUpdateSpriteHash(@sprites)
  end

  def pbChoose(commands)
    @sprites["cmdwindow"].commands = commands
    @sprites["cmdwindow"].resizeToFit(commands)
    loop do
      Graphics.update
      Input.update
      pbUpdate
      if Input.trigger?(Input::USE)
        return @sprites["cmdwindow"].index
      end
    end
  end

  def pbEndScene
    pbFadeOutAndHide(@sprites) { pbUpdate }
    pbDisposeSpriteHash(@sprites)
    @viewport.dispose
  end

  def pbCloseScene
    pbDisposeSpriteHash(@sprites)
    @viewport.dispose
  end
end

